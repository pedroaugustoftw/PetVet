import assert from'node:assert/strict';
import{readFile,stat}from'node:fs/promises';
import{preview}from'vite';
import{chromium}from'@playwright/test';
import sharp from'sharp';
import{siteUrl,basePath}from'./seo.mjs';
const html=await readFile('dist/index.html','utf8');
assert(!html.includes('<!-- PETVET_SEO -->'));
assert(html.includes('Av. Maria Jeanne Moeira Sampaio'));
assert(html.includes('Av. Antônio Procópio'));
assert(html.includes('31.032.434/0001-05'));
assert(html.includes('Clínica médica'));
const image=await sharp('dist/social/petvet-compartilhar-v1.jpg').metadata();
assert.equal(image.width,1200);assert.equal(image.height,630);
assert((await stat('dist/social/petvet-compartilhar-v1.jpg')).size<500000);
const server=await preview({preview:{host:'127.0.0.1',port:4175,strictPort:true}});
const browser=await chromium.launch({headless:true});
try{
 const context=await browser.newContext({javaScriptEnabled:false});
 const page=await context.newPage();
 const response=await page.goto('http://127.0.0.1:4175'+basePath,{waitUntil:'networkidle'});
 assert.equal(response.status(),200);
 assert.equal(await page.title(),'PetVet | Veterinária em Teotônio Vilela e Junqueiro');
 assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'),siteUrl);
 assert.equal(await page.locator('meta[property="og:url"]').getAttribute('content'),siteUrl);
 assert.equal(await page.locator('meta[property="og:image"]').getAttribute('content'),siteUrl+'social/petvet-compartilhar-v1.jpg');
 assert.equal(await page.locator('meta[name="twitter:card"]').getAttribute('content'),'summary_large_image');
 assert.equal(await page.locator('meta[name="description"]').count(),1);
 assert.equal(await page.locator('h1').count(),1);
 assert(await page.locator('h1').isVisible());
 assert(await page.locator('footer').isVisible());
 const data=JSON.parse(await page.locator('script[type="application/ld+json"]').textContent());
 const locations=data['@graph'].filter(x=>Array.isArray(x['@type'])&&x['@type'].includes('VeterinaryCare'));
 assert.equal(locations.length,2);
 assert.deepEqual(locations.map(x=>x.address.addressLocality),['Teotônio Vilela','Junqueiro']);
 assert(data['@graph'].some(x=>x['@type']==='WebSite'));
 for(const name of ['robots.txt','sitemap.xml','social/petvet-compartilhar-v1.jpg','icons/petvet-48.png','icons/petvet-180.png'])assert.equal((await context.request.get('http://127.0.0.1:4175'+basePath+name)).status(),200);
 const robots=await(await context.request.get('http://127.0.0.1:4175'+basePath+'robots.txt')).text();
 assert(robots.includes(`Sitemap: ${siteUrl}sitemap.xml`));
 assert((await readFile('dist/sitemap.xml','utf8')).includes(`<loc>${siteUrl}</loc>`));
 await context.close();
 const live=await browser.newContext({reducedMotion:'reduce'}),interactive=await live.newPage(),errors=[];
 interactive.on('pageerror',e=>errors.push(e.message));
 interactive.on('console',m=>{if(m.type()==='error'&&/hydrat|mismatch|react error/i.test(m.text()))errors.push(m.text())});
 await interactive.goto('http://127.0.0.1:4175'+basePath,{waitUntil:'networkidle'});
 await interactive.getByRole('button',{name:'Consulta veterinária'}).click();
 assert(await interactive.locator('dialog').isVisible());
 await interactive.keyboard.press('Escape');
 assert(!await interactive.locator('dialog').isVisible());
 assert.deepEqual(errors,[]);
 await live.close();
 console.log('PASS: public canonical/OG URLs, banner 1200×630, metadata, 2 veterinary locations, sitemap/robots/icons, content without JavaScript, and React hydration interactions.');
}finally{await browser.close();await new Promise(resolve=>server.httpServer.close(resolve))}
